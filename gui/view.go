package gui

// View is a user-defined view. Views are never displayed directly; a
// Layout is generated from the View. GenerateLayout returns the node's
// complete subtree — a view with children generates them itself, via
// appendChildViews.
//
// Pipeline: View -> generateViewLayout -> Layout ->
// layoutArrange -> renderLayout -> []RenderCmd
type View interface {
	GenerateLayout(w *Window) Layout
}

// ViewFunc adapts a function to a View, deferring construction to
// layout-generation time so the function can read window state. It is
// useful inside Content slices when a subtree needs State(*Window)
// but the enclosing function does not receive w.
type viewFunc func(*Window) View

// GenerateLayout calls the wrapped function and recursively
// builds the full Layout tree from the returned View.
func (f viewFunc) GenerateLayout(w *Window) Layout {
	v := f(w)
	if v == nil {
		return Layout{}
	}
	return generateViewLayout(v, w)
}

// ensureLayoutShape normalizes layout nodes so pipeline passes can
// safely dereference Shape fields.
func ensureLayoutShape(layout *Layout) {
	if layout == nil {
		return
	}
	if layout.Shape == nil {
		layout.Shape = &Shape{shapeType: shapeNone}
	}
}

// GenerateViewLayout builds the Layout tree for a View and normalizes
// the node's shape (ensureLayoutShape), so every pipeline pass can rely
// on a non-nil Shape.
//
// This is the supported entry point for composite View widgets. A
// widget package assembling a tree from child Views wants this one; a
// view that declares children uses appendChildViews to have the
// framework generate them.
func GenerateViewLayout(view View, w *Window) Layout {
	return generateViewLayout(view, w)
}

// generateViewLayout is the internal layout builder. The node's
// children — if it has any — were generated by its own
// GenerateLayout via appendChildViews; what this function owns is
// shape normalization and the identity stamp.
func generateViewLayout(view View, w *Window) Layout {
	// Depth cap shared with the layout, event and render walks
	// (maxEventDepth): a view tree nested past the budget yields a
	// placeholder rather than recursing until the stack gives out. The
	// placeholder is shapeNone, so the sizing passes skip it and the
	// container measures as if the subtree were absent — the same
	// degrade-the-frame semantics the capped walks take. genDepth is
	// the tree depth at entry (window_update brackets only the root
	// view function), so the boundary matches the walks exactly.
	if w != nil && w.viewState.genDepth > maxEventDepth {
		return layoutPlaceholder()
	}
	scope := ""
	// The depth is what lets EffID tell "no scope, top of the tree"
	// from "no scope, not generating at all". Every generation path
	// runs through here, so counting in one place covers them all.
	// Deferred, so a panic in a view function cannot leave the window
	// looking as if generation were still in progress.
	if w != nil {
		if w.viewState.genDepth == 0 {
			// Every root generation starts from an empty scope: the main
			// tree, and each overlay injectFloatingLayer builds at arrange
			// time. Cleared rather than assumed — a view function that
			// panics past the restore in appendChildViews would otherwise
			// prefix every later frame's identities with a stale scope,
			// silently and window-wide.
			w.viewState.idScope = ""
		}
		w.viewState.genDepth++
		defer func() { w.viewState.genDepth-- }()
		scope = w.viewState.idScope
	}
	layout := view.GenerateLayout(w)
	ensureLayoutShape(&layout)
	// Identity is stamped here, where the scope is known, and nowhere
	// afterwards.
	//
	// A shape a parent already stamped keeps that stamp: appendChildViews
	// resolved it against this same scope on its way past, and skipping
	// it here keeps the join to one lookup per ID-bearing widget. An
	// ID-bearing shape is stamped exactly when effID is non-empty, since
	// the join never answers "" for a non-empty leaf, so the two states
	// cannot be confused. A stale stamp carried over from an earlier
	// frame would survive this guard; DebugStampDrift is what reports
	// one.
	if s := layout.Shape; s.effID == "" {
		stampEffID(w, s, scope)
	}
	return layout
}

// maxChildViews caps how many direct children one container generates.
// Truncation happens here, at generation, which is the single enforcement
// point: the tree the rest of the frame sees is already within the cap,
// so layout, render and event dispatch need no separate check. Event
// dispatch used to re-check it and return early, which could only ever
// fire on a hand-built Layout and silently dropped that subtree's
// keyboard input when it did.
const maxChildViews = 10000

// appendChildViews generates children under parent's ID scope and
// appends them to parent.Children, after whatever the parent already
// put there.
//
// Ordering matters: the parent's own shape must be built before this is
// called, because the parent's ID resolves in the *enclosing* scope while
// its children resolve under it. Children the parent injected directly
// (addGroupBoxTitle's eraser + label) keep their position ahead of these.
func appendChildViews(w *Window, parent *Layout, children []View) {
	// Callers build parent.Shape before calling: childScopeID stamps it
	// and reads its ID to derive the child scope, and a shape built late
	// (or a nil shape — childScopeID's nil branch) silently generates
	// the children in the enclosing scope instead of under the parent.
	if len(children) == 0 {
		return
	}
	if len(children) > maxChildViews {
		children = children[:maxChildViews]
	}
	// Pre-size so append never reallocates; the reservation comes from the
	// frame-scoped arena (reset in resetViewPools) to avoid a per-node heap
	// allocation.
	wantCap := len(parent.Children) + len(children)
	if cap(parent.Children) < wantCap {
		var grown []Layout
		if w != nil {
			grown = w.scratch.takeLayoutChildren(wantCap)
		} else {
			grown = make([]Layout, 0, wantCap)
		}
		grown = grown[:len(parent.Children)]
		copy(grown, parent.Children)
		parent.Children = grown
	}
	// Saved and restored rather than recomputed on the way out: a sibling
	// must not inherit a child's scope.
	//
	// childScopeID stamps parent.Shape on the way past. This is the one
	// point that knows the parent's scope while the parent's own
	// generateViewLayout call is still in flight, which is why the
	// parent is stamped here rather than left to that call alone.
	saved := w.viewState.idScope
	w.viewState.idScope = childScopeID(w, saved, parent.Shape)
	for _, child := range children {
		if child == nil {
			continue
		}
		parent.Children = append(
			parent.Children,
			generateViewLayout(child, w),
		)
	}
	w.viewState.idScope = saved
}
