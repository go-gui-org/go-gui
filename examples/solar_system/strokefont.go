// glyphFor returns the glyph for an ASCII letter, upper or lower.
// It reports false if the character has no glyph (digits, punctuation).
func glyphFor(ch rune) (strokeGlyph, bool) {
	if ch >= 'A' && ch <= 'Z' {
		g := strokeFont[ch-'A']
		if len(g) == 0 {
			return nil, false
		}
		return g, true
	}
	if ch >= 'a' && ch <= 'z' {
		g := strokeFont[ch-'a']
		if len(g) == 0 {
			return nil, false
		}
		return g, true
	}
	return nil, false
}
